(() => {
  const products = Array.isArray(window.PINKA_PRODUCTS) ? window.PINKA_PRODUCTS : [];
  const grid = document.getElementById('marketGrid');
  if (!grid) return;

  const escapeHtml = (value = '') => String(value)
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('"', '&quot;')
    .replaceAll("'", '&#039;');

  const makeCard = (product, index) => {
    const id = product.id || `prompt-${index + 1}`;
    const title = product.title || `Prompt Product ${index + 1}`;
    const price = Number(product.price || 0);
    const category = product.category || 'prompt';
    const thumbnail = product.thumbnail || `assets/products/thumbnails/${id}.jpg`;
    const preview = product.preview || `assets/products/previews/${id}.jpg`;
    const coverClass = product.coverClass || 'cover-portrait';
    const badge = product.badge || 'PROMPT';
    const icon = product.icon || '✦';
    const coverTitle = Array.isArray(product.coverTitle) ? product.coverTitle : [product.coverTitle || title];
    const kicker = product.kicker || category.toUpperCase();
    const description = product.description || 'Premium Prompt product from PINKA Digital Academy.';
    const extra = index >= 3;

    const card = document.createElement('article');
    card.className = 'market-card product-card';
    card.dataset.category = category;
    card.dataset.title = title;
    card.dataset.price = String(price);
    card.dataset.productId = id;
    card.dataset.preview = preview;
    if (extra) {
      card.dataset.extra = 'true';
      card.hidden = true;
    }

    const titleHtml = coverTitle.map(part => escapeHtml(part)).join('<br>');
    card.innerHTML = `
      <div class="market-cover ${escapeHtml(coverClass)}">
        <img class="market-product-image" src="${escapeHtml(thumbnail)}" alt="${escapeHtml(title)}" loading="lazy">
        <div class="market-cover-overlay">
          <span class="cover-badge">${escapeHtml(badge)}</span>
          <div class="cover-scene">${escapeHtml(icon)}</div>
          <strong>${titleHtml}</strong>
        </div>
      </div>
      <div class="market-card-body">
        <span class="card-kicker">${escapeHtml(kicker)}</span>
        <h3>${escapeHtml(title)}</h3>
        <p>${escapeHtml(description)}</p>
        <div class="market-card-foot">
          <button class="market-buy buy-btn" type="button">ទិញ PROMPT</button>
          <button class="market-read preview-btn" type="button">មើលរូប</button>
        </div>
      </div>`;
    return card;
  };

  const fragment = document.createDocumentFragment();
  products.forEach((product, index) => fragment.appendChild(makeCard(product, index)));
  grid.replaceChildren(fragment);
})();
